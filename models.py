from fuel import FUELP
DEFAULTS = dict(km=15000, y=5, home=80, gas=FUELP["g95"], die=FUELP["die"], glp=FUELP["glp"], ph=0.15, pp=0.49)

def cost(c, S=DEFAULTS):
    """Coste total de tener el coche: pérdida de valor + energía + seguro + mantenimiento + impuesto."""
    rate = c["res"] ** (1 / 5); resid = c["p"] * rate ** S["y"]; dep = c["p"] - resid
    h = S["home"] / 100; elec = h * S["ph"] + (1 - h) * S["pp"]; km = S["km"] * S["y"]
    fuelp = {"g": S["gas"], "d": S["die"], "glp": S["glp"]}.get(c["f"], S["gas"])
    if c["t"] == "ev":
        energy = c["c"] / 100 * km * elec
    elif c["t"] == "phev":
        share = min(0.8, c["rng"] * 0.75 * 240 / S["km"]) * h
        energy = km * (share * 18 / 100 * S["ph"] + (1 - share) * c["c"] / 100 * fuelp)
    else:
        energy = c["c"] / 100 * km * fuelp
    ins, mnt, tax = c["ins"] * S["y"], c["mnt"] * S["y"], c["tax"] * S["y"]
    total = dep + energy + ins + mnt + tax
    return dict(dep=dep, energy=energy, ins=ins, mnt=mnt, tax=tax, total=total, resid=resid, perKm=total / km, month=total / S["y"] / 12)
